import type { AuditEvent, Incident } from "@/types";
import { MOCK_PIPELINE_SUMMARIES } from "@/data/mock/pipelineSummaries";
import { emailFor } from "@/data/mock/people";

/** The pipeline's actual owner is the single source of truth for who an incident/notification is addressed to. */
const OWNER_BY_PIPELINE_ID = new Map(MOCK_PIPELINE_SUMMARIES.map((p) => [p.id, p.owner]));

type IncidentDraft = Omit<Incident, "assigneeEmail">;

function withOwnerAttribution(incident: IncidentDraft): Incident {
  const owner = OWNER_BY_PIPELINE_ID.get(incident.pipelineId) ?? incident.assignee;
  return { ...incident, assignee: owner ?? null, assigneeEmail: owner ? emailFor(owner) : null };
}

/**
 * One hand-authored, fully worked incident per failure type (and its
 * rerun-succeeds / rerun-fails / partial-success sub-scenarios) — see
 * pipelineSummaries.ts's FIXED_INCIDENT_EXAMPLES for which (country,
 * category) each one is pinned to. Every failure type in the spec has at
 * least one real, complete example here; none are skipped.
 */
function audit(label: string, actor: AuditEvent["actor"], timestamp: string, detail: string | null = null): AuditEvent {
  return { id: `${label}-${timestamp}`.toLowerCase().replace(/[^a-z0-9]+/g, "-"), timestamp, label, actor, detail };
}

