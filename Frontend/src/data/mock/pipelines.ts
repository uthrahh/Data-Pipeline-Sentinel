function buildFillerExecutions(): PipelineExecution[] {
  const filler: PipelineExecution[] = [];
  for (let i = 0; i < 40; i += 1) {
    const spec = FILLER_PIPELINES[i % FILLER_PIPELINES.length];
    const country = FILLER_COUNTRIES[i % FILLER_COUNTRIES.length];
    const hour = (2 + Math.floor(i / 4)) % 24;
    const minute = (i * 7) % 60;
    const durationMinutes = 5 + ((i * 3) % 15);
    const startTime = `2026-09-15T${String(hour).padStart(2, "0")}:${String(minute).padStart(2, "0")}:00Z`;
    const endDate = new Date(startTime);
    endDate.setMinutes(endDate.getMinutes() + durationMinutes);

    filler.push({
      runId: `RUN-fill-${(1000 + i).toString(16)}`,
      pipelineId: spec.id,
      pipelineName: spec.name,
      status: "SUCCESS",
      trigger:
        spec.id === "procurement_processing"
          ? { type: "Dependency", name: "Triggered by Job 1 completion" }
          : spec.id === "gold_integration"
            ? { type: "Dependency", name: "Triggered by Job 2 completion" }
            : { type: "Scheduled", name: spec.id === "sales_processing" ? "Nightly Sales Order Extract" : "Nightly Material Master Load" },
      startTime,
      endTime: endDate.toISOString(),
      durationMinutes,
      country,
      environment: "PROD",
      owner: spec.owner,
      slaMinutes: spec.slaMinutes,
      errorCode: null,
      errorMessage: null,
      incidentId: null,
    });
  }
  return filler;
}

